const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, it };

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem("lupus-locale");
    if (stored === "en" || stored === "it") return stored;
  } catch {
    // Storage can be unavailable: fall back to the browser language.
  }
  return navigator.language.toLowerCase().startsWith("it") ? "it" : "en";
}

export const locale = ref<Locale>(initialLocale());

export function setLocale(next: Locale): void {
  locale.value = next;
  document.documentElement.lang = next;
  try {
    localStorage.setItem("lupus-locale", next);
  } catch {
    // The choice simply is not remembered.
  }
}

document.documentElement.lang = locale.value;

/** Translates a message. Reading `locale` makes templates update when the language changes. */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return dictionaries[locale.value][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? ""),
  );
}
